function setLanguage(language) {
  const lang = language === 'en' ? 'en' : 'zh';
  const text = copy[lang];
  document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  const url = new URL(location.href);
  url.searchParams.set('lang', lang);
  history.replaceState(null, '', url);
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = text[el.dataset.i18n]; });
  document.querySelectorAll('[data-i18n-alt]').forEach(el => { el.alt = text[el.dataset.i18nAlt]; });
  document.querySelectorAll('[data-lang]').forEach(el => el.setAttribute('aria-pressed', String(el.dataset.lang === lang)));
  document.title = text.title;
  ['description','og:description','twitter:description'].forEach(key => document.querySelector(`meta[name="${key}"],meta[property="${key}"]`).content = text.meta);
  ['og:title','twitter:title'].forEach(key => document.querySelector(`meta[name="${key}"],meta[property="${key}"]`).content = text.title);
  document.querySelector('meta[property="og:locale"]').content = lang === 'zh' ? 'zh_CN' : 'en_US';
  try { localStorage.setItem('stela-pages-language', lang); } catch {}
}
document.querySelectorAll('[data-lang]').forEach(el => el.addEventListener('click', () => setLanguage(el.dataset.lang)));
let preferred = new URLSearchParams(location.search).get('lang');
if (!preferred) { try { preferred = localStorage.getItem('stela-pages-language'); } catch {} }
setLanguage(preferred || (navigator.language.startsWith('zh') ? 'zh' : 'en'));
